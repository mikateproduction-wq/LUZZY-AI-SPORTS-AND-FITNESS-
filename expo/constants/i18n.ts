function format(template: string, vars?: Record<string, string | number>) {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_m, key: string) => {
    const v = vars[key];
    return typeof v === 'string' || typeof v === 'number' ? String(v) : '';
  });
}

export function t(key: Key, language: LanguageCode, vars?: Record<string, string | number>) {
  const fallbackDict = (DICTS[DEFAULT_LANGUAGE] ?? DICTS.en) as Dict;
  const dict = (DICTS[language] ?? fallbackDict) as Dict;
  return format(dict[key] ?? fallbackDict[key] ?? key, vars);
}
